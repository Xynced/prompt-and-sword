/** Спасбросок pf2e: Стойкость, Реакция, Воля. */
export type SaveKind = 'fort' | 'ref' | 'will';

/**
 * Защиты юнита (план damage-types). Четыре защиты pf2e — КБ против ударов,
 * три спасброска против эффектов — плюс плоские сопротивления, слабости и
 * иммунитеты по типам; порядок их применения — `applyDefenses` в tuning.ts
 * (иммунитет → слабость → сопротивление).
 *
 * Масштаб плоских чисел здесь свой: удар в этом симе — 2–7 hp, поэтому числа
 * pf2e (5/10) были бы выключателем. Рабочий диапазон — сопротивление 1–3,
 * слабость 2–4. Умолчания защит — `DEFAULT_AC` / `DEFAULT_SAVE` в tuning.ts.
 */
export interface Defenses {
  /** КБ: против него бросается атака. */
  ac?: number;
  /** Стойкость — яд и прочее телесное. */
  fort?: number;
  /** Реакция — площадные касты. */
  ref?: number;
  /** Воля — воздействия на разум. */
  will?: number;
  /** −N урона этого типа. */
  resist?: Partial<Record<DamageType, number>>;
  /** +N урона этого типа. */
  weak?: Partial<Record<DamageType, number>>;
  /** Урон этого типа обнуляется целиком. */
  immune?: DamageType[];
}

/**
 * Длящийся урон (план damage-types, волна 6) — райдер приёма или площадной
 * формы: горение, кровотечение, яд. Вешается только дошедшим ударом, крит
 * удваивает (правило pf2e), у площадных — только проваленным спасброском.
 *
 * `type` отдельно от типа самого удара намеренно: отравленный кинжал ранит
 * колющим, а тлеет в жертве ядом — и сопротивление яду гасит именно тление,
 * не удар.
 */
export interface PersistSpec {
  /** Урон за тик; рабочий диапазон 1–2 (обоснование — `PERSIST_DC` в tuning.ts). */
  dmg: number;
  /** Тип тления, если отличается от типа удара. */
  type?: DamageType;
}

/** Тлеющий на юните длящийся урон: по записи на тип (тот же тип не стакается). */
export interface Persist {
  type: DamageType;
  dmg: number;
  /**
   * Помощь подоспела (assisted recovery pf2e): ближайшая проверка гасится
   * по PERSIST_DC_ASSISTED вместо PERSIST_DC. Снимается самой проверкой.
   */
  assisted?: boolean;
}

/** Прямоугольная зона задачи боя (план objectives, волна 2): рубеж, выход, берег. */
export interface Zone {
  x1: number;
  y1: number;
  x2: number;
  y2: number;
}

/** Что юнит может сделать за очко хода. Цены — `AP_COST`/`apCostFor` в scoring.ts. */
export type ActionKind =
  | 'move'
  | 'carefulStep'
  | 'weakAttack'
  | 'attack'
  | 'selflessAttack'
  | 'shove'
  | 'aoeBlast'
  | 'aoeLine'
  | 'aoeRitual'
  | 'rage'
  | 'wall'
  | 'heal'
  | 'bless'
  | 'feint'
  | 'cover'
  | 'fullCover'
  | 'shieldAlly'
