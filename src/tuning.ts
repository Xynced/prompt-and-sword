/**
 * Глобальный тюнинг темпа боя. Вынесен отдельно, чтобы battle и scoring
 * (battle импортирует scoring) считали урон одной формулой без цикла импортов.
 */

/**
 * Множитель урона. Меньше — длиннее бой: условным правилам (hp ниже X,
 * бой затянулся, союзник в опасности) нужно время, чтобы успеть выстрелить.
 * Цель — 10–14 раундов на типовой бой.
 */
export const DMG_SCALE = 0.6;

/** Ожидаемый урон от atk с учётом глобального множителя — для скоринга. */
export function expectedDamage(atk: number): number {
  return atk * DMG_SCALE;
}

/** Очков действия на ход. */
export const AP_PER_TURN = 3;

/**
 * Слабый удар (1 AP) против обычного (2 AP). Меньше 0.5, иначе три слабых
 * удара (1.5 базового) обгоняли бы «удар + слабый» (1.4) и дешёвая атака
 * доминировала бы всегда — пока в игре нет MAP из pf2e, эта нелинейность
 * единственная её сдерживает. Но и заметно меньше 0.5 нельзя: при 0.4 три
 * слабых удара (1.2) настолько уступали связке (1.4), что тяга характера к
 * частым ударам становилась чистым штрафом — горячка теряла четверть побед.
 * 0.45 держит обе стороны: волюм чуть слабее, но играбелен.
 */
export const WEAK_ATK_MULT = 0.45;

/**
 * Отчаянный удар (2 AP): бьёт сильнее, но открывает до своего следующего хода.
 * Уязвимость ниже прибавки к урону намеренно — при равных 1.5/1.5 размен был
 * убыточен для всех (бьёшь одного, получаешь ×1.5 от всех четверых), и линза,
 * тянущая к нему, оказывалась проклятием: фанатик терял 24 очка винрейта.
 * Но и слишком дёшево нельзя: на 1.25 отчаянный удар становится лучшим ударом
 * за очко в игре, его начинают жать все подряд и характер перестаёт читаться.
 */
export const SELFLESS_ATK_MULT = 1.5;
export const SELFLESS_VULN_MULT = 1.35;

/** Доля снятого входящего урона: прикрыться (1 AP) и глухая защита (3 AP). */
export const COVER = 0.25;
export const FULL_COVER = 2 / 3;

/**
 * Рипост глухой обороны (план защиты): ближний удар по юниту с
 * coverLevel ≥ FULL_COVER ранит бьющего на фиксированные очки. Строго без
 * rng (прецедент шипов: новый вызов rng сдвинул бы все фикстуры). Оборона
 * конвертирует настойчивость бьющего в его раны — пауза становится разменом.
 */
export const RIPOSTE_DMG = 4;

/**
 * Высота (план поля): стрелку (range > 1) холм даёт +height к дальности, а
 * высота 2 — ещё и плоский бонус к урону («бью сверху»). Ближний бой высота
 * не меняет осознанно: иначе холм обязателен всем и бой сводится к драке за
 * одну клетку.
 */
export const HIGH_GROUND_DMG = 1;

/**
 * Каменное укрытие (план поля): доля урона, снятая укрытием при выстреле в
 * укрытую цель. Не запрет выстрела и НЕ складывается с прикрытием от действий
 * (берётся максимум): стрелок не выключается из боя, а получает повод сменить
 * позицию. Стрелок на высоте 2 бьёт поверх укрытия.
 */
export const TERRAIN_COVER = 0.5;

/**
 * Опасная клетка (план поля): фиксированный урон тому, кто закончил на ней
 * действие «шаг» (проход насквозь и осторожный шаг безопасны). Строго без
 * rng: любой новый вызов rng() сдвинул бы всю последовательность боя и
 * переписал существующие фикстуры. ~1 удар среднего бойца.
 */
export const HAZARD_DMG = 4;

/**
 * Цена одного очка действия в единицах скоринга: действие выбирается по
 * `сумма факторов − AP × AP_VALUE`. Главный рычаг «копить или тратить»:
 * выше — охотнее дешёвые действия, ниже — охотнее дорогие.
 */
export const AP_VALUE = 0.5;

/**
 * Аффинность оружия к манере удара (план классов): родная манера +бонус,
 * чуждая −бонус. Намеренно меньше STRIKE_STYLE_BONUS (2.5): оружие — вкус,
 * слово игрока — приказ; «бить отчаянно» перебивает нелюбовь щита к
 * отчаянному, но без приказа щитник сам к нему не тянется.
 */
export const WEAPON_AFFINITY_BONUS = 1.2;

/**
 * Во сколько очков скоринга обходится единица тяги характера к действию
 * (`actionBias`): слагаемое `(тяга − 1) × ACTION_BIAS_WEIGHT`.
 *
 * Именно слагаемое, а не множитель. Множитель на инстинкт вёл себя ровно
 * наоборот нужного: у прикрытия своего слагаемого в скоринге почти нет, и
 * трус с ×2.5 уходил в глухую защиту в 98% ходов, — а выбор между слабым и
 * обычным ударом перебивается премией правила, и там множитель не было видно
 * вовсе. Тяга — это вкус характера, он не должен зависеть от того, насколько
 * велики прочие слагаемые в этой конкретной позиции.
 */
export const ACTION_BIAS_WEIGHT = 2;
