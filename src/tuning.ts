/** Ловкое оружие (agile pf2e: кинжалы, кулаки, парные ножи) — ступень мягче. */
export const MAP_STEP_AGILE = 4;
/** Пассив следопыта-стрелка (hunter's edge flurry): вся лестница мягче на две. */
export const MAP_STEP_FLURRY = 3;
export const MAP_STEP_FLURRY_AGILE = 2;

/**
 * Стойка «бить часто» (план words) против MAP: ступень штрафа мягче на
 * единицу. Без этого слово о частых ударах заказывало ровно то, что MAP
 * штрафует, и становилось ловушкой — замер аудита после ввода MAP: −23% к
 * наиву против −15% до него. Смягчение возвращает форсированному темпу
 * паритет со свободной связкой «большой удар + добор», и слово наконец
 * означает технику скорострельности, а не просто выбор вида атаки.
 */
export const OFTEN_STANCE_MAP_RELIEF = 1;

/**
 * Штраф к броску атаки: `strikes` — сколько ударов юнит уже сделал за этот
 * ход. Ступеней две, как в pf2e: дальше третьего удара штраф не растёт.
 */
export function mapPenalty(
  strikes: number,
  opts: { agile?: boolean; flurry?: boolean; often?: boolean } = {},
): number {
  const base = opts.flurry
    ? opts.agile
      ? MAP_STEP_FLURRY_AGILE
      : MAP_STEP_FLURRY
    : opts.agile
      ? MAP_STEP_AGILE
      : MAP_STEP;
  const step = Math.max(base - (opts.often ? OFTEN_STANCE_MAP_RELIEF : 0), MAP_STEP_FLURRY_AGILE);
  return Math.min(Math.max(strikes, 0), 2) * step;
}

/*
 * Длящийся урон (план damage-types, волна 6). Тикает в конце хода жертвы,
 * гасится флэт-чеком — как в pf2e, включая помощь со стороны.
 */

/**
 * Флэт-чек гашения: d20 ≥ 15 в конце хода снимает тление. Число pf2e взято
 * как есть: 30% на проверку — это 3.3 тика ожидания, и от них зависит вся
 * цена райдера. Помощь (действие «сбить пламя», своё или чужое) роняет DC до
 * 10, то есть 55% — вдвое короче тление и вдвое дешевле рана.
 */
export const PERSIST_DC = 15;
export const PERSIST_DC_ASSISTED = 10;

/**
 * Рабочий урон тика — 1–2. Первый тик гарантирован, дальше ожидание 3.3 тика,
 * поэтому тление на 1 стоит ~3.3 hp — примерно полный удар среднего бойца, а
 * на 2 уже два с половиной. Второй ограничитель — правило pf2e «тот же тип не
 * складывается»: поджечь горящего нечем, и приём окупается один раз на цель.
 */
export function persistEndChance(dc: number = PERSIST_DC): number {
  return (21 - dc) / 20;
}

/** Ожидаемое число тиков тления: первый гарантирован, дальше геометрия флэт-чека. */
export function persistTicks(dc: number = PERSIST_DC): number {
  return 1 / persistEndChance(dc);
}

/**
 * Ожидание, когда ближайшая проверка идёт по сниженному DC, а дальнейшие — по
 * обычному: ровно это покупает одно очко хода, потраченное на помощь.
 */
export function persistTicksAssisted(): number {
  return 1 + (1 - persistEndChance(PERSIST_DC_ASSISTED)) * persistTicks(PERSIST_DC);
}

/**
 * Скидка скоринга на «потом»: длящийся урон не убивает сейчас, бой может
 * кончиться раньше, а цель — умереть от чужого удара. Без скидки поджигатель
 * предпочитал тление даже добивающему удару.
 */
export const PERSIST_DISCOUNT = 0.6;

/**
 * Типы урона, гасящие регенерацию (pf2e: тролль и огонь с кислотой). Любой
 * урон этих типов — удар, зона или тление — съедает ближайший тик заращивания.
 */
export const REGEN_QUENCH: readonly DamageType[] = ['fire', 'acid'];

/**
 * Ожидаемый множитель урона по всем 20 граням — для скоринга: он обязан
 * оценивать удар так же, как бой его исполнит, иначе выбор цели и оружия
 * поедет. Перебор, а не формула: степень считает та же `degreeOf`.
 */
function expectedMult(bonus: number, dc: number, table: Record<Degree, number>): number {
  let sum = 0;
  for (let natural = 1; natural <= 20; natural++) sum += table[degreeOf(natural, natural + bonus, dc)];
  return sum / 20;
}

/** Ожидаемая доля урона удара с бонусом bonus по цели с КБ ac (промахи и криты внутри). */
export function expectedAttackMult(bonus: number, ac: number): number {
  return expectedMult(bonus, ac, ATTACK_MULT);
}

/** Ожидаемая доля урона площадного каста по цели со спасброском save. */
export function expectedSaveMult(save: number, dc: number = SAVE_DC): number {
  return expectedMult(save, dc, BASIC_SAVE_MULT);
}

/**
 * Во сколько снятого урона обходится бонус к КБ (план armor): доля, на которую
 * падает ожидание удара, если к КБ ac прибавить bonus.
 *
 * Нужна скорингу: решения об обороне («прикрыться или ударить», «кого крыть
 * щитом») он взвешивает в долях maxHp, а бой считает промахами. Без общего
 * перевода инстинкт прикрытия остался бы в валюте, которой в бою больше нет.
 * Бонус атаки по умолчанию — типовой враг: точнее было бы считать по каждому
 * угрожающему, но угроза в скоринге и так суммарная.
 */
export function guardMitigation(bonus: number, ac: number = DEFAULT_AC, atk: number = DEFAULT_ATK_BONUS): number {
  if (bonus <= 0) return 0;
  const open = expectedAttackMult(atk, ac);
  return open <= 0 ? 0 : Math.max(0, 1 - expectedAttackMult(atk, ac + bonus) / open);
}

/** Насколько прибавка обороны с `from` до `to` снимает урона — разница долей. */
export function guardGain(from: number, to: number, ac: number = DEFAULT_AC): number {
  return Math.max(0, guardMitigation(to, ac) - guardMitigation(from, ac));
}
/*
 * Нерв (план nerve) — режим seeded-разброса весов решения. Все константы
 * работают только при включённом режиме: при `nerve = 0` ни одна из них не
 * участвует в счёте, и бой считается ровно как до плана.
 */
/**
 * Амплитуда разброса по умолчанию (тумблер UI/debug): множитель слагаемого —
 * `max(0, 1 + amp × pressure × бросок)`, бросок треугольный в [-1, 1]. Крайности
 * броска редки, а при типичном давлении ~0.2 разброс держится в пределах ±30%;
 * загнанный боец (давление 1) может слагаемое и вовсе потерять из виду.
 *
 * Замер по каталогу отладочных боёв (22 боя × 15 сидов, партия без характеров):
 * 1 — режим почти не виден (расхождение с детерминированной линией лишь к 70%
 * длины боя, исход менялся в 3% боёв); 2 — заметно, но тянет винрейт партии
 * +1.5пп (63.0 → 64.5); 1.5 — середина и ноль по балансу: расхождение к 58%
 * длины, исход менялся в 4% боёв, винрейт 63.0% против тех же 63.0% базы.
 */
export const NERVE_AMP = 1.5;
/** Доля давления от раны: на нуле hp — полный вклад. */
export const NERVE_HURT = 0.5;
/** Доля давления от тесноты: два врага в контакте — полный вклад. */
export const NERVE_CROWD = 0.4;
/**
 * Вклад «нет приказа на ситуацию»: боец достраивает ход инстинктами, и именно
 * там разброс уместнее всего — своей формулировки игрок здесь не давал.
 */
export const NERVE_BLIND = 0.4;

/**
 * Уровень важности фразы, который считается **фокусом** (план nerve): вес
 * растёт как обычно (×1.5 за уровень), и сверх того боец держится за такой
 * приказ — режим нерва шатает его решения вдвое слабее (NERVE_FOCUS_CALM).
 * Фокус — рычаг игрока против разброса: без него сильные слова в панике
 * пропадали бы наравне с фоновыми инстинктами.
 */
export const FOCUS_WEIGHT = 3;
export const NERVE_FOCUS_CALM = 0.5;
