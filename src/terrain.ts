/**
 * Схема боя от сида внутри пула по тегу: детерминированно, без RNG (сид уже
 * перемешан снаружи). Ранние слои получают простые схемы, поздние — все,
 * у элиты и босса свои пулы.
 */
export function pickTerrain(seed: number, tag: ArenaTag = 'late'): TerrainLayout {
  const pool = TERRAIN_LAYOUTS.filter((l) => l.tags.includes(tag));
  return pool[Math.abs(seed) % pool.length]!;
}

/** Свойства клетки схемы (вне поля — пустая клетка). */
export function tileAt(tiles: readonly Tile[][], p: Pos): Tile {
  return tiles[p.y]?.[p.x] ?? {};
}
