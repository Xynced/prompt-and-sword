import type { Pos } from './types.js';

/**
 * Террейн: поле 18×18 из клеток со свойствами. Схема выбирается детерминированно
 * от сида боя внутри пула по тегу узла — спарринг «те же кости» играет на той же
 * карте. Каждая арена — не россыпь камней, а поставленный вопрос (`scenario`).
 *
 * Правила схем:
 *  - колонки x ≤ 2 (зона партии) и x ≥ 15 (зона врагов) полностью свободны;
 *  - сегменты стен короткие либо с широкими проходами — глухих мешков не строим;
 *  - ранний пул (`early`) без высоты и опасных клеток: поле открывается вместе
 *    со словами, первые бои не требуют словаря, которого у игрока ещё нет.
 *
 * В шаге 1 плана поля механика есть только у `blocked` (движение + LoS);
 * высота, опасность и труднопроходимость — данные под шаги 2–5.
 */

export type HazardKind = 'spikes' | 'fire';

export type ArenaTag = 'early' | 'late' | 'elite' | 'boss';

export interface Tile {
  /** Камень/стена: не пройти, не видно насквозь; источник укрытия. */
  blocked?: boolean;
  /** Высота клетки; по умолчанию 0. */
  height?: 0 | 1 | 2;
  /** Опасная клетка: урон тому, кто на ней остался. */
  hazard?: HazardKind;
  /** Труднопроходимая: вход стоит 2 очка движения. */
  rough?: boolean;
}

export interface TerrainLayout {
  name: string;
  /** Одна строка: какое решение эта арена ставит. Идёт в разведку. */
  scenario: string;
  /** Пулы подбора: ранние слои, поздние, элита, босс. */
  tags: ArenaTag[];
  /** Клетки [y][x], 18×18. */
  tiles: Tile[][];
}

export const ARENA_W = 18;
export const ARENA_H = 18;

/** Колонки зон развёртывания: партия x ≤ 2, враги x ≥ 15. */
export const PARTY_ZONE_MAX_X = 2;
export const FOE_ZONE_MIN_X = 15;

const CHAR_TILE: Record<string, Tile> = {
  '.': {},
  '#': { blocked: true },
  '1': { height: 1 },
  '2': { height: 2 },
  '^': { hazard: 'spikes' },
  '*': { hazard: 'fire' },
  '~': { rough: true },
};

/** ASCII-схема → клетки; свежие объекты на каждую клетку (бой мутирует копию). */
function parseTiles(rows: readonly string[]): Tile[][] {
  if (rows.length !== ARENA_H) throw new Error(`Схема должна иметь ${ARENA_H} строк, а не ${rows.length}`);
  return rows.map((row, y) => {
    if (row.length !== ARENA_W) throw new Error(`Строка ${y} должна иметь ${ARENA_W} клеток, а не ${row.length}`);
    return [...row].map((ch, x) => {
      const tile = CHAR_TILE[ch];
      if (!tile) throw new Error(`Неизвестный символ схемы «${ch}» в (${x},${y})`);
      return { ...tile };
    });
  });
}

function arena(name: string, scenario: string, tags: ArenaTag[], rows: readonly string[]): TerrainLayout {
  return { name, scenario, tags, tiles: parseTiles(rows) };
}

