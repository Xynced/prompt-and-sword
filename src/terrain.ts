import type { Pos } from './types.js';

/**
 * Террейн: камни блокируют движение и линию видимости. Схема выбирается
 * детерминированно от сида боя — спарринг «те же кости» играет на той же карте.
 *
 * Правила схем:
 *  - колонки x ≤ 2 и x ≥ 9 свободны (зоны спавна партии и врагов);
 *  - сегменты стен короткие (≤3) либо с широкими проходами — тяга к цели
 *    ходит по BFS-полю, но глухие мешки всё равно не строим.
 */

export interface TerrainLayout {
  name: string;
  tiles: Pos[];
}

const p = (x: number, y: number): Pos => ({ x, y });

export const TERRAIN_LAYOUTS: readonly TerrainLayout[] = [
  {
    // почти чистое поле — базовая геометрия, пара ориентиров
    name: 'поляна',
    tiles: [p(5, 3), p(6, 8)],
  },
  {
    // рассыпь камней в центре: ломает прямые заходы, даёт укрытия от стрелков
    name: 'валуны',
    tiles: [p(4, 4), p(5, 4), p(7, 2), p(6, 7), p(7, 7), p(4, 9)],
  },
  {
    // стена по центру с тремя проходами (y 0–1, 5–6, 10–11) — узкие места
    name: 'частокол',
    tiles: [p(6, 2), p(6, 3), p(6, 4), p(6, 7), p(6, 8), p(6, 9)],
  },
  {
    // два разрушенных угла + обломок в центре: коридоры и фланговые дуги
    name: 'руины',
    tiles: [p(4, 2), p(5, 2), p(4, 3), p(6, 5), p(7, 5), p(6, 9), p(7, 9), p(7, 8)],
  },
];

/** Схема боя от сида: детерминированно, без RNG (сид уже перемешан снаружи). */
export function pickTerrain(seed: number): TerrainLayout {
  return TERRAIN_LAYOUTS[Math.abs(seed) % TERRAIN_LAYOUTS.length]!;
}
